"""Scripts handed to an offline GPU host alongside images and models.

Each one needs bash and coreutils (plus tar, and podman where it loads or
runs something) and nothing from LayerSmith: the receiving host has no
network and no Python to rely on. Everything a script checks - names, sizes,
checksums - is written into it, so it works even if the checksum files are
left behind.
"""

import shlex

from layersmith import config

quote = shlex.quote


def _array(values) -> str:
    return "\n".join(f"  {quote(str(value))}" for value in values)


def _fill(template: str, values: dict) -> str:
    for key, value in values.items():
        template = template.replace(f"@@{key}@@", value)
    return template


# ------------------------------------------------------------ install model

INSTALL_MODEL = r"""#!/usr/bin/env bash
# install-@@NAME@@.sh - generated by LayerSmith @@VERSION@@
#
# Installs the model @@REPO@@ (revision @@REVISION_SHORT@@) into
# <models dir>/@@NAME@@ from its @@COUNT@@ part(s), then checks every file
# against the sha256 recorded when LayerSmith downloaded it.
#
#   ./install-@@NAME@@.sh                      into /opt/models (or $MODELS_DIR)
#   ./install-@@NAME@@.sh --dir /data/models
#
# Options:
#   --dir DIR        models directory (default: $MODELS_DIR or /opt/models)
#   --parts-dir DIR  where the parts are (default: this script's directory)
#   --remove-parts   delete the parts once the model is installed and verified
#   --force          replace an existing folder of that name that differs
#   -h, --help       this text
#
# Exit codes: 0 ok, 1 usage, 2 missing part, 3 corrupt, 4 not enough space
# or write error, 5 an existing folder differs.

set -u -o pipefail

NAME=@@NAME_Q@@
REPO=@@REPO_Q@@
REVISION=@@REVISION_Q@@
MODEL_SIZE=@@MODEL_SIZE@@
PART_NAMES=(
@@PART_NAMES@@
)
PART_SIZES=(
@@PART_SIZES@@
)
PART_SHA256=(
@@PART_SHA256@@
)
FILE_NAMES=(
@@FILE_NAMES@@
)
FILE_SIZES=(
@@FILE_SIZES@@
)
FILE_SHA256=(
@@FILE_SHA256@@
)

models_dir=${MODELS_DIR:-/opt/models} remove_parts=0 force=0
parts_dir=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
while [ $# -gt 0 ]; do
  case "$1" in
    --dir) [ $# -ge 2 ] || { echo "--dir needs a directory" >&2; exit 1; }; models_dir=$2; shift ;;
    --parts-dir) [ $# -ge 2 ] || { echo "--parts-dir needs a directory" >&2; exit 1; }; parts_dir=$2; shift ;;
    --remove-parts) remove_parts=1 ;;
    --force) force=1 ;;
    -h|--help) sed -n '2,/^$/s/^# \{0,1\}//p' "${BASH_SOURCE[0]}"; exit 0 ;;
    *) echo "Unknown option: $1 (try --help)" >&2; exit 1 ;;
  esac
  shift
done

if command -v sha256sum >/dev/null 2>&1; then sha256() { sha256sum "$@"; }
elif command -v shasum >/dev/null 2>&1; then sha256() { shasum -a 256 "$@"; }
else echo "Neither sha256sum nor shasum is installed" >&2; exit 1
fi
command -v tar >/dev/null 2>&1 || { echo "tar is not installed" >&2; exit 1; }
first_field() { local line; read -r line; printf '%s\n' "${line%% *}"; }
size_of() { wc -c <"$1" | tr -d ' '; }
fail() { echo "FAILED"; echo; printf '%s\n' "$@" >&2; echo >&2; }

# Every file of the model folder in DIR has the recorded size and sha256.
verify_files() {
  local dir=$1 i bad=()
  for i in "${!FILE_NAMES[@]}"; do
    if [ ! -f "$dir/${FILE_NAMES[$i]}" ] || [ "$(size_of "$dir/${FILE_NAMES[$i]}")" != "${FILE_SIZES[$i]}" ] ||
       [ "$(sha256 "$dir/${FILE_NAMES[$i]}" | first_field)" != "${FILE_SHA256[$i]}" ]; then
      bad+=("${FILE_NAMES[$i]}")
    fi
  done
  [ ${#bad[@]} -eq 0 ] && return 0
  printf '%s\n' "${bad[@]}"
  return 1
}

target="$models_dir/$NAME"
remove_the_parts() {
  [ "$remove_parts" = 1 ] || return 0
  (cd "$parts_dir" && rm -f -- "${PART_NAMES[@]}") && echo "Removed the ${#PART_NAMES[@]} part(s)."
}
done_message() {
  echo
  echo "Model installed: $target"
  echo "In the GPU benchmark container: /models/$NAME"
  echo "  gpu-bench llm --model /models/$NAME"
}

if [ -d "$target" ]; then
  printf 'Found %s, verifying... ' "$target"
  if verify_files "$target" >/dev/null; then
    echo "OK (already installed)"; remove_the_parts; done_message; exit 0
  elif [ "$force" != 1 ]; then
    fail "$target exists but is not this model (or is incomplete)." \
         "Move it away, or re-run with --force to replace it."
    exit 5
  fi
  echo "differs, replacing it (--force)"
fi

printf 'Checking model parts... '
missing=() wrong=()
for i in "${!PART_NAMES[@]}"; do
  part="$parts_dir/${PART_NAMES[$i]}"
  if [ ! -f "$part" ]; then missing+=("${PART_NAMES[$i]}")
  elif [ "$(size_of "$part")" != "${PART_SIZES[$i]}" ]; then wrong+=("${PART_NAMES[$i]}")
  fi
done
if [ ${#missing[@]} -gt 0 ] || [ ${#wrong[@]} -gt 0 ]; then
  fail "${#PART_NAMES[@]} part(s) expected in $parts_dir." \
       ${missing[@]+"${missing[@]/#/  missing: }"} \
       ${wrong[@]+"${wrong[@]/#/  incomplete: }"} \
       "Copy the missing or incomplete part(s) again, then re-run this script."
  exit 2
fi
echo "OK (${#PART_NAMES[@]} parts)"

printf 'Verifying checksums... '
corrupt=()
for i in "${!PART_NAMES[@]}"; do
  [ "$(sha256 "$parts_dir/${PART_NAMES[$i]}" | first_field)" = "${PART_SHA256[$i]}" ] || corrupt+=("${PART_NAMES[$i]}")
done
if [ ${#corrupt[@]} -gt 0 ]; then
  fail "Checksum mismatch, the file(s) are corrupt:" "${corrupt[@]/#/  corrupt: }" \
       "Copy the corrupt part(s) again, then re-run this script."
  exit 3
fi
echo OK

# Only a directory this script creates is handed to the user; an existing
# one is never chowned (think --dir /opt).
if [ ! -d "$models_dir" ] && ! mkdir -p "$models_dir" 2>/dev/null; then
  echo "Creating $models_dir needs sudo:"
  { sudo mkdir -p "$models_dir" && sudo chown "$(id -u):$(id -g)" "$models_dir"; } ||
    { echo "Cannot create $models_dir; use --dir" >&2; exit 4; }
fi
[ -w "$models_dir" ] || { echo "$models_dir is not writable by $(id -un); use --dir, or fix its permissions" >&2; exit 4; }
free=$(df -Pk "$models_dir" 2>/dev/null | awk 'NR==2 {print $4}')
if [ -n "$free" ] && [ $((free * 1024)) -lt "$MODEL_SIZE" ]; then
  printf 'Unpacking model... '
  fail "Not enough space in $models_dir: $((MODEL_SIZE / 1000000)) MB needed, $((free * 1024 / 1000000)) MB free." \
       "Free space, or use --dir on a larger volume."
  exit 4
fi

staging="$models_dir/.$NAME.partial.$$"
cleanup() { rm -rf -- "$staging"; }
trap cleanup EXIT
trap 'echo; echo "Interrupted; nothing was installed." >&2; exit 130' INT TERM
mkdir -p "$staging" || { echo "Cannot write $models_dir" >&2; exit 4; }

printf 'Unpacking model... '
if ! (cd "$parts_dir" && cat -- "${PART_NAMES[@]}") | tar -xf - -C "$staging" --no-same-owner; then
  fail "Unpacking into $staging failed (disk full or read-only?)."
  exit 4
fi
echo OK

printf 'Verifying model files... '
if ! mismatched=$(verify_files "$staging/$NAME"); then
  fail "These files do not match what LayerSmith downloaded:" "$mismatched"
  exit 3
fi
echo OK

[ -d "$target" ] && rm -rf -- "$target"
mv -- "$staging/$NAME" "$target" || { echo "Could not move the model to $target" >&2; exit 4; }
remove_the_parts
echo
echo "$REPO ($REVISION)"
done_message
"""


def install_model(model, parts: dict) -> str:
    return _fill(INSTALL_MODEL, {
        "VERSION": config.VERSION, "NAME": model.name, "NAME_Q": quote(model.name),
        "REPO": model.repo_id, "REPO_Q": quote(model.repo_id),
        "REVISION_SHORT": (model.revision or "")[:12], "REVISION_Q": quote(model.revision or ""),
        "COUNT": str(len(parts["parts"])), "MODEL_SIZE": str(sum(int(f["size"]) for f in model.files)),
        "PART_NAMES": _array(p["name"] for p in parts["parts"]),
        "PART_SIZES": _array(int(p["size"]) for p in parts["parts"]),
        "PART_SHA256": _array(p["sha256"] for p in parts["parts"]),
        "FILE_NAMES": _array(f["name"] for f in model.files),
        "FILE_SIZES": _array(int(f["size"]) for f in model.files),
        "FILE_SHA256": _array(f["sha256"] for f in model.files),
    })


# --------------------------------------------------------- start container

START_CONTAINER = r"""#!/usr/bin/env bash
# start_container.sh - generated by LayerSmith @@VERSION@@
#
# Starts the GPU benchmark container @@IMAGE@@.
#
#   ./start_container.sh                    dashboard (TUI)
#   ./start_container.sh gpu-bench info     any gpu-bench command instead
#   ./start_container.sh gpu-bench full --model /models/<model>
#
# Change the defaults with environment variables, for example
#   MODELS_DIR=/data/models GPUS=0 ./start_container.sh
#   PODMAN_ARGS="-e NCCL_DEBUG=INFO" ./start_container.sh   extra podman run options
set -euo pipefail

IMAGE=${IMAGE:-@@IMAGE_Q@@}
MODELS_DIR=${MODELS_DIR:-/opt/models}        # Hugging Face model folders (config.json + *.safetensors)
RESULTS_DIR=${RESULTS_DIR:-/opt/gpu-results} # one folder per run ends up here
GPUS=${GPUS:-all}                            # all, or one GPU: 0, 1, ...
SHM_SIZE=${SHM_SIZE:-16g}
CACHE_DIR=${CACHE_DIR:-$RESULTS_DIR/.cache}  # kernels vLLM/FlashInfer/Triton compile, kept between runs

die() { echo "ERROR: $*" >&2; exit 1; }

command -v podman >/dev/null || die "podman is not installed"
podman image exists "$IMAGE" || die "image $IMAGE is not loaded (run ./setup.sh, or podman load -i the archive)"
nvidia-ctk cdi list 2>/dev/null | grep -q "nvidia.com/gpu=$GPUS" ||
  die "nvidia.com/gpu=$GPUS is not in the CDI spec; run: sudo nvidia-ctk cdi generate --output=/etc/cdi/nvidia.yaml"

# Only a directory created here is handed to the user; an existing one is
# never chowned.
if [ ! -d "$RESULTS_DIR" ] && ! mkdir -p "$RESULTS_DIR" 2>/dev/null; then
  sudo mkdir -p "$RESULTS_DIR" && sudo chown "$(id -u):$(id -g)" "$RESULTS_DIR"
fi
[ -w "$RESULTS_DIR" ] || die "$RESULTS_DIR is not writable by $(id -un); set RESULTS_DIR or fix its permissions"

mkdir -p "$CACHE_DIR" || die "cannot create $CACHE_DIR; set CACHE_DIR"
mounts=(-v "$RESULTS_DIR:/results" -v "$CACHE_DIR:/cache")
if [ -d "$MODELS_DIR" ]; then
  mounts+=(-v "$MODELS_DIR:/models:ro")
else
  echo "NOTE: $MODELS_DIR does not exist - starting without models (LLM tests unavailable)." >&2
fi

# -it only with a terminal, so this also works from cron or Slurm.
tty=()
[ -t 0 ] && [ -t 1 ] && tty=(-it)
# shellcheck disable=SC2206 # PODMAN_ARGS is split into words on purpose
extra=(${PODMAN_ARGS:-})

exec podman run --rm ${tty[@]+"${tty[@]}"} \
  --name gpu-benchmark \
  --device "nvidia.com/gpu=$GPUS" \
  --security-opt=label=disable \
  --shm-size="$SHM_SIZE" \
  "${mounts[@]}" \
  ${extra[@]+"${extra[@]}"} \
  "$IMAGE" "$@"
"""


def start_container(image: str) -> str:
    return _fill(START_CONTAINER, {"VERSION": config.VERSION, "IMAGE": image, "IMAGE_Q": quote(image)})


# ------------------------------------------------------------------ setup

SETUP = r"""#!/usr/bin/env bash
# setup.sh - generated by LayerSmith @@VERSION@@
#
# One command on the GPU host: checks disk space, restores and loads the
# image @@IMAGE@@, installs @@MODEL_COUNT@@ model(s) into the models
# directory, checks the NVIDIA Container Toolkit, then starts the dashboard.
# Every step is skipped when it is already done, so it is safe to re-run.
#
#   chmod +x *.sh && ./setup.sh
#
# Options:
#   --models-dir DIR   where models go (default: $MODELS_DIR or /opt/models)
#   --results-dir DIR  where results go (default: /opt/gpu-results)
#   --keep-parts       keep the parts after restoring (default: delete them)
#   --no-start         prepare everything, do not start the container
#   -h, --help         this text
#
# Podman unpacks the archive in $TMPDIR (default /var/tmp) while loading;
# point TMPDIR at a larger disk if that one is small.

set -u -o pipefail

IMAGE=@@IMAGE_Q@@
IMAGE_ID=@@IMAGE_ID_Q@@
ARCHIVE=@@ARCHIVE_Q@@
ARCHIVE_SIZE=@@ARCHIVE_SIZE@@
IMAGE_SIZE=@@IMAGE_SIZE@@
MODELS=(
@@MODELS@@
)
MODEL_SIZES=(
@@MODEL_SIZES@@
)

MODELS_DIR=${MODELS_DIR:-/opt/models} RESULTS_DIR=${RESULTS_DIR:-/opt/gpu-results}
keep_parts=0 start=1
while [ $# -gt 0 ]; do
  case "$1" in
    --models-dir) [ $# -ge 2 ] || { echo "--models-dir needs a directory" >&2; exit 1; }; MODELS_DIR=$2; shift ;;
    --results-dir) [ $# -ge 2 ] || { echo "--results-dir needs a directory" >&2; exit 1; }; RESULTS_DIR=$2; shift ;;
    --keep-parts) keep_parts=1 ;;
    --no-start) start=0 ;;
    -h|--help) sed -n '2,/^$/s/^# \{0,1\}//p' "${BASH_SOURCE[0]}"; exit 0 ;;
    *) echo "Unknown option: $1 (try --help)" >&2; exit 1 ;;
  esac
  shift
done
cd "$(dirname "${BASH_SOURCE[0]}")" || exit 1
export MODELS_DIR RESULTS_DIR
tmp=${TMPDIR:-/var/tmp}
remove=(--remove-parts); [ "$keep_parts" = 1 ] && remove=()
step() { echo; echo "== $*"; }
die() { echo "ERROR: $*" >&2; exit "${2:-1}"; }

step "1/5 Checking the host"
for tool in podman tar sha256sum df; do
  command -v "$tool" >/dev/null 2>&1 || die "$tool is not installed"
done
if command -v nvidia-smi >/dev/null 2>&1 && nvidia-smi -L >/dev/null 2>&1; then
  nvidia-smi -L | sed 's/^/  /'
else
  echo "  WARNING: nvidia-smi does not work - the NVIDIA driver is missing or not loaded."
fi

loaded=0
if podman image exists "$IMAGE" 2>/dev/null; then
  have=$(podman image inspect --format '{{.Id}}' "$IMAGE" 2>/dev/null)
  want=${IMAGE_ID#sha256:}
  if [ -z "$want" ] || [ "${have#sha256:}" = "$want" ]; then loaded=1; fi
fi

# Space: what each step still needs, added up per filesystem.
declare -A need=() where=()
gb() { awk -v b="$1" 'BEGIN { printf "%.1f", b / 1e9 }'; }
mount_of() { df -P "$1" 2>/dev/null | awk 'NR==2 {print $6}'; }
existing_parent() { local d=$1; while [ ! -d "$d" ]; do d=$(dirname "$d"); done; printf '%s\n' "$d"; }
add_need() {
  local mount; mount=$(mount_of "$(existing_parent "$1")")
  [ -n "$mount" ] || return 0
  need[$mount]=$(( ${need[$mount]:-0} + $2 )); where[$mount]="${where[$mount]:-}${where[$mount]:+, }$3"
}
if [ "$loaded" = 0 ]; then
  [ -f "$ARCHIVE" ] || add_need . "$ARCHIVE_SIZE" "image archive"
  add_need "$tmp" "$ARCHIVE_SIZE" "podman load scratch ($tmp)"
  graphroot=$(podman info --format '{{.Store.GraphRoot}}' 2>/dev/null)
  [ -n "$graphroot" ] && add_need "$graphroot" "$IMAGE_SIZE" "image store ($graphroot)"
fi
for i in "${!MODELS[@]}"; do
  [ -d "$MODELS_DIR/${MODELS[$i]}" ] || add_need "$MODELS_DIR" "${MODEL_SIZES[$i]}" "${MODELS[$i]}"
done
short=0
for mount in "${!need[@]}"; do
  free=$(( $(df -Pk "$mount" | awk 'NR==2 {print $4}') * 1024 ))
  status=OK; [ "$free" -lt "${need[$mount]}" ] && { status="NOT ENOUGH"; short=1; }
  printf '  %-24s needs %7s GB, %7s GB free  %s  (%s)\n' "$mount" "$(gb "${need[$mount]}")" "$(gb "$free")" \
    "$status" "${where[$mount]}"
done
if [ "$short" = 1 ]; then
  die "Not enough disk space. Free space, or use --models-dir and TMPDIR=... on a larger disk." 4
fi

step "2/5 Image $IMAGE"
if [ "$loaded" = 1 ]; then
  echo "  already loaded"
else
  bash ./assemble-image.sh ${remove[@]+"${remove[@]}"} || die "restoring the image archive failed" 2
  echo "+ TMPDIR=$tmp podman load -i $ARCHIVE"
  TMPDIR=$tmp podman load -i "$ARCHIVE" || die "podman load failed" 6
  podman image exists "$IMAGE" || die "$IMAGE is not in podman after loading" 6
  echo "  loaded; $ARCHIVE can be deleted now if you need the space"
fi

step "3/5 Models in $MODELS_DIR"
[ ${#MODELS[@]} -eq 0 ] && echo "  none in this kit"
for name in ${MODELS[@]+"${MODELS[@]}"}; do
  echo "-- $name"
  bash "./install-$name.sh" --dir "$MODELS_DIR" ${remove[@]+"${remove[@]}"} || die "installing $name failed" 3
done

step "4/5 NVIDIA Container Toolkit (CDI)"
if nvidia-ctk cdi list 2>/dev/null | grep -q 'nvidia.com/gpu=all'; then
  echo "  nvidia.com/gpu=all is available"
elif command -v nvidia-ctk >/dev/null 2>&1; then
  echo "+ sudo nvidia-ctk cdi generate --output=/etc/cdi/nvidia.yaml"
  sudo nvidia-ctk cdi generate --output=/etc/cdi/nvidia.yaml || die "generating the CDI spec failed" 7
  nvidia-ctk cdi list | grep -q 'nvidia.com/gpu=all' || die "the CDI spec has no nvidia.com/gpu=all - is the driver loaded?" 7
else
  die "nvidia-ctk is not installed. Install the NVIDIA Container Toolkit (package nvidia-container-toolkit), then re-run." 7
fi

step "5/5 Ready"
echo "  Image:   $IMAGE"
echo "  Models:  $MODELS_DIR (in the container: /models)"
for name in ${MODELS[@]+"${MODELS[@]}"}; do echo "           /models/$name"; done
echo "  Results: $RESULTS_DIR"
echo
echo "  Start again later with: bash start_container.sh"
[ "$start" = 1 ] || exit 0
exec bash ./start_container.sh
"""


def setup(image: str, image_id: str | None, archive: str, archive_size: int, image_size: int,
          models: list[tuple[str, int]]) -> str:
    return _fill(SETUP, {
        "VERSION": config.VERSION, "IMAGE": image, "IMAGE_Q": quote(image), "IMAGE_ID_Q": quote(image_id or ""),
        "ARCHIVE_Q": quote(archive), "ARCHIVE_SIZE": str(int(archive_size)), "IMAGE_SIZE": str(int(image_size)),
        "MODEL_COUNT": str(len(models)),
        "MODELS": _array(name for name, _ in models), "MODEL_SIZES": _array(size for _, size in models),
    })


# ---------------------------------------------------------- download all

DOWNLOAD_ALL = r"""#!/usr/bin/env bash
# download-all.sh - generated by LayerSmith @@VERSION@@
#
# Downloads every file of "@@TITLE@@" (@@COUNT@@ files, @@TOTAL_GB@@ GB) from
# LayerSmith into the current directory, resuming interrupted downloads and
# checking each part's sha256. Then copy the directory to the GPU host.
#
#   ./download-all.sh [LAYERSMITH_URL]      (default: @@SERVER@@)

set -u -o pipefail
server=${1:-@@SERVER_Q@@}
server=${server%/}
FILES=(
@@FILES@@
)
command -v curl >/dev/null 2>&1 || { echo "curl is not installed" >&2; exit 1; }
if command -v sha256sum >/dev/null 2>&1; then sha256() { sha256sum "$@"; }
else sha256() { shasum -a 256 "$@"; }
fi
size_of() { wc -c <"$1" | tr -d ' '; }

failed=0 n=0
for entry in "${FILES[@]}"; do
  IFS='|' read -r path name size sum <<<"$entry"
  n=$((n + 1))
  if [ -f "$name" ] && { [ -z "$size" ] || [ "$(size_of "$name")" = "$size" ]; } &&
     { [ -z "$sum" ] || [ "$(sha256 "$name" | cut -d' ' -f1)" = "$sum" ]; }; then
    printf '[%d/%d] %s already here\n' "$n" "${#FILES[@]}" "$name"; continue
  fi
  printf '[%d/%d] %s\n' "$n" "${#FILES[@]}" "$name"
  if ! curl -fL --progress-bar --retry 5 --retry-delay 3 -C - -o "$name.partial" "$server$path"; then
    echo "  FAILED to download $name" >&2; failed=$((failed + 1)); continue
  fi
  if [ -n "$sum" ] && [ "$(sha256 "$name.partial" | cut -d' ' -f1)" != "$sum" ]; then
    echo "  checksum mismatch for $name, removed; run again" >&2; rm -f "$name.partial"; failed=$((failed + 1)); continue
  fi
  mv -f "$name.partial" "$name"
done
chmod +x ./*.sh 2>/dev/null
if [ "$failed" -gt 0 ]; then echo; echo "$failed file(s) failed; run ./download-all.sh again to retry." >&2; exit 1; fi
echo
echo "All ${#FILES[@]} files downloaded and verified."
echo "Copy this directory to the GPU host and run: @@NEXT@@"
"""


def download_all(title: str, server: str, files: list[dict], next_step: str) -> str:
    """files: [{"url": "/api/...", "name", "size", "sha256"?}]."""
    total = sum(int(f.get("size") or 0) for f in files)
    return _fill(DOWNLOAD_ALL, {
        "VERSION": config.VERSION, "TITLE": title.replace("\n", " "), "COUNT": str(len(files)),
        "TOTAL_GB": f"{total / 1e9:.1f}", "SERVER": server, "SERVER_Q": quote(server), "NEXT": next_step,
        "FILES": _array(f"{f['url']}|{f['name']}|{f.get('size') or ''}|{f.get('sha256') or ''}" for f in files),
    })
