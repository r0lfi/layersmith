def test_clone_copies_the_definition_but_not_the_builds(client):
    project = client.post("/api/projects", json={
        "name": "network-tools", "template": "Network Tools",
        "spec": {"base": {"distribution": "AlmaLinux", "version": "10"}}}).json()
    build = client.post(f"/api/projects/{project['id']}/builds", json={}).json()
    run_pending_build(client, build["id"])

    clone = client.post(f"/api/projects/{project['id']}/clone", json={"name": "network-tools-custom"}).json()
    assert clone["spec"] == project["spec"] and clone["repository"] == "layersmith/network-tools-custom"
    assert client.get(f"/api/projects/{clone['id']}").json()["builds"] == []


def test_invalid_input_is_rejected_with_a_message(client):
    bad_name = client.post("/api/projects", json={"name": "Not A Valid Name", "template": "Minimal",
                                                  "spec": {"base": {"distribution": "Alpine", "version": "3.22"}}})
    assert bad_name.status_code == 422

    secret = client.post("/api/preview", json={"name": "x", "template": "Minimal", "spec": {
        "base": {"distribution": "Alpine", "version": "3.22"},
        "env": [{"name": "REGISTRY_TOKEN", "value": "abc"}]}})
    assert secret.status_code == 422 and "runtime" in secret.json()["detail"]


