def test_upload_is_content_addressed(client):
    first = client.post("/api/uploads", files={"file": ("config.yml", b"key: value")}).json()
    second = client.post("/api/uploads", files={"file": ("other-name.yml", b"key: value")}).json()
    assert first["sha256"] == second["sha256"] and first["size"] == len(b"key: value")
    assert (client.state["settings"].upload_dir / first["sha256"]).read_bytes() == b"key: value"


def test_download_refuses_paths_outside_the_image_directory(client):
    project = client.post("/api/projects", json={
        "name": "app", "template": "Minimal", "spec": {"base": {"distribution": "Alpine", "version": "3.22"}}}).json()
    build = client.post(f"/api/projects/{project['id']}/builds", json={}).json()
    run_pending_build(client, build["id"])

    with client.state["session_factory"]() as session:
        row = session.get(Build, build["id"])
        row.export_path = "/etc/passwd"
        session.commit()
    assert client.get(f"/api/builds/{build['id']}/download/export").status_code == 404


def test_settings_reports_paths_and_backend_state(client):
    body = client.get("/api/settings").json()
    assert body["app_name"] == "LayerSmith" and body["tagline"]
    fields = {row["field"] for row in body["paths"]}
    assert fields == {"data_dir", "image_dir", "build_dir", "upload_dir", "log_dir", "tmp_dir"}
    # The data directory holds the database, so it is never editable here.
    assert [row["editable"] for row in body["paths"] if row["field"] == "data_dir"] == [False]
    assert all(row["path"].startswith("/") for row in body["paths"])
    assert body["storage"]["total"] > 0 and "available" in body["build_backend"]


def test_build_log_websocket_replays_then_closes_for_finished_builds(client):
    project = client.post("/api/projects", json={
        "name": "app", "template": "Minimal", "spec": {"base": {"distribution": "Alpine", "version": "3.22"}}}).json()
    build = client.post(f"/api/projects/{project['id']}/builds", json={}).json()
    run_pending_build(client, build["id"])

    with client.websocket_connect(f"/api/builds/{build['id']}/logs") as websocket:
        messages = [websocket.receive_json() for _ in range(3)]
    assert messages[0]["type"] == "log" and "LayerSmith" in messages[0]["line"]
